def exp3_grid() -> np.ndarray:
    W = np.linspace(0.65, 1.55, 6)
    belief = np.array([-0.8, -0.25, 0.25, 0.8])
    prev_signal = np.array([-1.0, 0.0, 1.0])
    signal = np.array([-1.0, 0.0, 1.0])
    return np.array([[w, b, ps, s] for w in W for b in belief for ps in prev_signal for s in signal], dtype=float)


def exp3_actions(method: str) -> np.ndarray:
    lev = np.array([-1.20, -0.45, 0.45, 1.20])
    bnext = np.array([-0.8, -0.25, 0.25, 0.8])
    theta = np.array([0.10, 0.25, 0.35, 0.65, 0.95]) if method == 'nbo_full_ndu' else np.array([0.25])
    return np.array([[l, th, bn] for l in lev for th in theta for bn in bnext], dtype=float)


def exp3_weights(action: np.ndarray, signal: np.ndarray, assets: int = 12) -> np.ndarray:
    leverage, theta, bnext = action[:, 0], action[:, 1], action[:, 2]
    alphas = np.linspace(0.04, 0.09, assets)
    betas = np.linspace(0.6, 1.6, assets)
    alpha_dev = alphas - alphas.mean()
    beta_dev = betas - betas.mean()
    mix = 0.60 * bnext + 0.40 * signal
    raw = alpha_dev[None, :] + beta_dev[None, :] * mix[:, None] + 0.55 * (theta[:, None] - 0.25) * (alpha_dev[None, :] + 0.55 * beta_dev[None, :] * signal[:, None])
    raw = raw - raw.mean(axis=1, keepdims=True)
    return leverage[:, None] * raw / (np.sum(np.abs(raw), axis=1, keepdims=True) + 1e-8)


def exp3_spec(method: str) -> NBOSpec:
    horizon = 50
    dt = 1.0 / horizon
    shocks = np.array([[fz, iz] for fz in (-1.0, 0.0, 1.0) for iz in (-1.0, 1.0)], dtype=float)
    assets = 12
    alphas = np.linspace(0.04, 0.09, assets)
    betas = np.linspace(0.6, 1.6, assets)
    idio = np.linspace(0.10, 0.22, assets)

    def terminal(X):
        return np.zeros(X.shape[0])

    def tr(step, X, action, shock):
        W, belief, prev_signal, signal = X[:, 0], X[:, 1], X[:, 2], X[:, 3]
        action_mat = np.repeat(action[None, :], X.shape[0], axis=0)
        weights = exp3_weights(action_mat, signal, assets=assets)
        theta = action[1]
        bnext = action[2]
        fz, iz = shock
        factor = 0.92 * belief + 0.18 * fz
        eps = iz * np.ones((X.shape[0], assets))
        asset_rets = alphas[None, :] * dt + betas[None, :] * factor[:, None] * dt + idio[None, :] * math.sqrt(dt) * eps
        turnover = np.sum(np.abs(weights), axis=1)
        port_ret = np.sum(weights * asset_rets, axis=1) - 0.0025 * turnover
        Wn = np.maximum(W * np.maximum(1.0 + port_ret, 1e-4), 1e-5)
        signal_next = 0.4 * signal + factor + 0.25 * iz
        reward = ((1.0 + 0.40 * theta) * np.log(np.maximum(1.0 + port_ret, 1e-6))
                  - 0.07 * (theta - 0.25) ** 2
                  - 0.0015 * turnover)
        return np.stack([np.clip(Wn, 0.35, 2.2), np.clip(bnext, -1.2, 1.2) * np.ones_like(Wn), np.clip(signal, -1.5, 1.5), np.clip(signal_next, -1.5, 1.5)], axis=1), reward

    return NBOSpec('exp3_high_dimensional_allocation', method, horizon, exp3_grid(), exp3_actions(method), shocks, tr, terminal)


def eval_exp3(policy: NBOResult, seed: int, episodes: int = 256, assets: int = 12) -> dict[str, float]:
    rng = np.random.default_rng(seed)
    steps = 50
    dt = 1.0 / steps
    alphas = np.linspace(0.04, 0.09, assets)
    betas = np.linspace(0.6, 1.6, assets)
    idio = np.linspace(0.10, 0.22, assets)
    W = np.full(episodes, 1.0)
