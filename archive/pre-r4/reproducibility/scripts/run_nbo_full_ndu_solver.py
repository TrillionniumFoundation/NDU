def exp1_grid() -> np.ndarray:
    W = np.linspace(0.35, 1.85, 13)
    h = np.linspace(0.025, 0.24, 11)
    return np.array([[w, hh] for w in W for hh in h], dtype=float)


def exp1_actions(method: str) -> np.ndarray:
    pis = np.array([-0.60, -0.15, 0.35, 0.85, 1.20])
    cfracs = np.array([0.030, 0.060, 0.095, 0.135, 0.170])
    thetas = np.array([0.08, 0.25, 0.55, 0.85, 1.00]) if method == 'nbo_full_ndu' else np.array([0.25])
    if method == 'nbo_preference_only':
        return np.array([[0.55, 0.070, th] for th in thetas], dtype=float)
    return np.array([[pi, cf, th] for pi in pis for cf in cfracs for th in thetas], dtype=float)


def exp1_spec(method: str) -> NBOSpec:
    horizon = 40
    dt = 1.0 / horizon
    shocks = np.array([-1.5, -0.5, 0.0, 0.5, 1.5])

    def terminal(X):
        return 0.45 * np.log(np.maximum(X[:, 0], 1e-5))

    def tr(step, X, action, z):
        W = X[:, 0]
        h = X[:, 1]
        pi, cfrac, theta = action
        if method == 'nbo_preference_only':
            surplus_pressure = np.clip(h / np.maximum(W, 1e-4), 0.0, 1.0)
            pi_eff = np.clip(0.75 - 1.2 * surplus_pressure, -0.5, 1.0)
            cfrac_eff = 0.045 + 0.03 * (1.0 - surplus_pressure)
        else:
            pi_eff = pi
            cfrac_eff = cfrac
        mu = 0.11 if step < horizon // 2 else -0.05
        sigma = 0.16 if step < horizon // 2 else 0.36
        c = np.maximum(1e-5, cfrac_eff * np.maximum(W, 1e-4))
        dW = (0.02 * W + pi_eff * W * (mu - 0.02) - c) * dt + pi_eff * W * sigma * math.sqrt(dt) * z
        Wn = np.maximum(W + dW, 1e-5)
        hn = np.maximum(h + theta * (c - h) * dt, 1e-5)
        surplus = c - h
        ruined = (surplus <= 1e-4) | (Wn <= 1e-5)
        reward = ((1.0 + 0.65 * theta) * np.log(np.maximum(surplus, 1e-4))
                  - 0.10 * (theta - 0.25) ** 2
                  - 0.02 * pi_eff ** 2
                  - 0.01 * (c / np.maximum(W, 1e-4)) ** 2) * dt
        reward = np.where(ruined, reward - 2.5, reward)
        return np.stack([np.clip(Wn, 0.25, 2.05), np.clip(hn, 0.015, 0.30)], axis=1), reward

    return NBOSpec('exp1_habit_portfolio', method, horizon, exp1_grid(), exp1_actions(method), shocks.reshape(-1, 1), tr, terminal)


def eval_exp1(policy: NBOResult, seed: int, episodes: int = 256) -> dict[str, float]:
    rng = np.random.default_rng(seed)
    steps = 40
    dt = 1.0 / steps
    shock = steps // 2
    W = np.full(episodes, 1.0)
    h = np.full(episodes, 0.08)
    ruined = np.zeros(episodes, dtype=bool)
    total_reward = np.zeros(episodes)
    mean_surplus_ratio = np.zeros(episodes)
    surplus_counts = np.zeros(episodes)
    theta_paths = []
    W_paths = [W.copy()]
    h_paths = [h.copy()]
    for t in range(steps):
        action = nbo_actions(policy, t, np.stack([W, h], axis=1))
        pi, cfrac, theta = action[:, 0], action[:, 1], action[:, 2]
        if policy.method == 'nbo_preference_only':
            surplus_pressure = np.clip(h / np.maximum(W, 1e-4), 0.0, 1.0)
            pi = np.clip(0.75 - 1.2 * surplus_pressure, -0.5, 1.0)
            cfrac = 0.045 + 0.03 * (1.0 - surplus_pressure)
        mu = 0.11 if t < shock else -0.05
        sigma = 0.16 if t < shock else 0.36
        z = rng.standard_normal(episodes)
        c = np.maximum(1e-5, cfrac * np.maximum(W, 1e-4))
        dW = (0.02 * W + pi * W * (mu - 0.02) - c) * dt + pi * W * sigma * math.sqrt(dt) * z
        W_new = np.maximum(W + dW, 1e-5)
        h_new = np.maximum(h + theta * (c - h) * dt, 1e-5)
        surplus = c - h
        newly_ruined = (surplus <= 1e-4) | (W_new <= 1e-5)
        reward = ((1.0 + 0.65 * theta) * np.log(np.maximum(surplus, 1e-4))
                  - 0.10 * (theta - 0.25) ** 2
                  - 0.02 * pi ** 2
                  - 0.01 * (c / np.maximum(W, 1e-4)) ** 2) * dt
        reward = np.where(newly_ruined, reward - 2.5, reward)
        # Continue the rollout after first breach rather than zeroing future
        # rewards; this avoids making early ruin artificially attractive.
        total_reward += reward
        ruined = ruined | newly_ruined
        ratio = np.maximum(surplus, 0.0) / np.maximum(W, 1e-4)
        mean_surplus_ratio += np.where(newly_ruined, 0.0, ratio)
        surplus_counts += (~newly_ruined).astype(float)
        W = W_new
        h = h_new
        theta_paths.append(theta.copy())
        W_paths.append(W.copy())
        h_paths.append(h.copy())
    total_reward += 0.45 * np.log(np.maximum(W, 1e-5))
    theta_paths = np.stack(theta_paths, axis=1)
    W_paths = np.stack(W_paths, axis=1)
    h_paths = np.stack(h_paths, axis=1)
    surplus_ratio = mean_surplus_ratio / np.maximum(surplus_counts, 1.0)
    pre = theta_paths[:, max(0, shock - 1)]
    lag = np.full(episodes, steps - shock, dtype=float)
    for j in range(episodes):
        idx = np.where(theta_paths[j, shock:] > pre[j] + 0.10)[0]
        if idx.size:
            lag[j] = float(idx[0])
    return {
        'mean_utility': float(total_reward.mean()),
        'cew': float(np.exp(total_reward.mean()) - 1.0),
        'ruin_prob': float(ruined.mean()),
        'surplus_ratio': float(surplus_ratio.mean()),
        'adaptation_lag': float(lag.mean() / steps),
        'wealth_terminal': float(W.mean()),
        'theta_std': float(theta_paths.std()),
    }


