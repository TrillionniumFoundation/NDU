def sigmoid(x):
    return 1.0 / (1.0 + np.exp(-np.clip(x, -40.0, 40.0)))


def annualized_sharpe(returns, dt):
    mu = returns.mean(axis=1)
    sd = np.maximum(returns.std(axis=1), 1e-3)
    return np.sqrt(1.0 / dt) * mu / sd


def max_drawdown(paths):
    peaks = np.maximum.accumulate(paths, axis=1)
    dd = paths / np.maximum(peaks, 1e-12) - 1.0
    return dd.min(axis=1)


def seed_values(base: int) -> list[int]:
    return [base + SEED_STRIDE * (j + 1) for j in range(SEED_COUNT)]


class ValueRegressor:
    """Small tensor/random-feature trunk used for compact Bellman-image audits."""

    def __init__(self, X: np.ndarray, y: np.ndarray, *, seed: int, width: int = 64, ridge: float = 1e-5) -> None:
        self.mean = X.mean(axis=0)
        self.std = X.std(axis=0) + 1e-6
        d = X.shape[1]
        rng = np.random.default_rng(seed)
        self.W = rng.normal(0.0, 0.85, size=(d, width))
        self.b = rng.normal(0.0, 0.60, size=width)
        Phi = self.features(X)
        A = Phi.T @ Phi + ridge * np.eye(Phi.shape[1])
        rhs = Phi.T @ y
        self.coef = np.linalg.solve(A, rhs)

    @classmethod
    def constant(cls, value: float, dim: int) -> 'ValueRegressor':
        obj = cls.__new__(cls)
        obj.mean = np.zeros(dim)
        obj.std = np.ones(dim)
        obj.W = np.zeros((dim, 1))
        obj.b = np.zeros(1)
        obj.coef = np.array([value, 0.0, 0.0, 0.0])
        return obj

    def features(self, X: np.ndarray) -> np.ndarray:
        Z = (X - self.mean) / self.std
        parts = [np.ones((X.shape[0], 1)), Z, Z * Z, np.tanh(Z @ self.W + self.b)]
        return np.concatenate(parts, axis=1)

    def predict(self, X: np.ndarray) -> np.ndarray:
        return self.features(np.asarray(X, dtype=float)) @ self.coef


@dataclass
class NBOResult:
    values: list[ValueRegressor]
    state_grid: np.ndarray
    action_tables: list[np.ndarray]
    actions: np.ndarray
    residuals: list[float]
    experiment: str
    method: str
    horizon: int
    state_dim: int
    action_dim: int
    sensor_count: int
    action_count: int
    shock_count: int


@dataclass
class NBOSpec:
    experiment: str
    method: str
    horizon: int
    state_grid: np.ndarray
    actions: np.ndarray
    shocks: np.ndarray
    transition_reward: Callable[[int, np.ndarray, np.ndarray, np.ndarray], tuple[np.ndarray, np.ndarray]]
    terminal: Callable[[np.ndarray], np.ndarray]


def nearest_rows(grid: np.ndarray, X: np.ndarray) -> np.ndarray:
    scale = grid.std(axis=0) + 1e-6
    Zg = grid / scale
    Zx = X / scale
    # Chunk to avoid large temporary arrays.
    idx = np.empty(X.shape[0], dtype=int)
    for start in range(0, X.shape[0], 4096):
        chunk = Zx[start:start + 4096]
        dist = ((chunk[:, None, :] - Zg[None, :, :]) ** 2).sum(axis=2)
        idx[start:start + len(chunk)] = np.argmin(dist, axis=1)
    return idx


def solve_nbo(spec: NBOSpec, *, seed: int = 20260512, width: int = 64) -> NBOResult:
    X = spec.state_grid
    dim = X.shape[1]
    next_value = ValueRegressor.constant(0.0, dim)
    values_rev: list[ValueRegressor] = []
    action_tables_rev: list[np.ndarray] = []
    residuals_rev: list[float] = []
    # Terminal value is represented by a fitted value regressor on the same sensors.
    terminal_y = spec.terminal(X)
    next_value = ValueRegressor(X, terminal_y, seed=seed + 10_000, width=width)
    for step in range(spec.horizon - 1, -1, -1):
        q_cols = []
        for action in spec.actions:
            accum = np.zeros(X.shape[0])
            for shock in spec.shocks:
                Xn, reward = spec.transition_reward(step, X, action, shock)
                accum += reward + next_value.predict(Xn)
            q_cols.append(accum / max(1, len(spec.shocks)))
        Q = np.stack(q_cols, axis=1)
        best_idx = np.argmax(Q, axis=1)
        target = Q[np.arange(X.shape[0]), best_idx]
        fit = ValueRegressor(X, target, seed=seed + step + 137 * (1 + len(values_rev)), width=width)
        pred = fit.predict(X)
        rmse = float(np.sqrt(np.mean((pred - target) ** 2)))
        residuals_rev.append(rmse)
        action_tables_rev.append(best_idx.astype(int))
        values_rev.append(fit)
        next_value = fit
    return NBOResult(
        values=list(reversed(values_rev)),
        state_grid=X,
        action_tables=list(reversed(action_tables_rev)),
        actions=spec.actions,
        residuals=list(reversed(residuals_rev)),
        experiment=spec.experiment,
        method=spec.method,
        horizon=spec.horizon,
        state_dim=dim,
        action_dim=spec.actions.shape[1],
        sensor_count=X.shape[0],
        action_count=spec.actions.shape[0],
        shock_count=spec.shocks.shape[0],
    )


def nbo_actions(policy: NBOResult, t: int, states: np.ndarray) -> np.ndarray:
    idx = nearest_rows(policy.state_grid, states)
    aidx = policy.action_tables[min(t, policy.horizon - 1)][idx]
    return policy.actions[aidx]


