def inv_grid() -> np.ndarray:
    inv = np.array([0.0, 12.0, 26.0, 42.0, 65.0])
    backlog = np.array([0.0, 8.0, 20.0, 36.0])
    ewma = np.array([14.0, 22.0, 32.0])
    last = np.array([14.0, 22.0, 34.0])
    return np.array([[i, b, e, l] for i in inv for b in backlog for e in ewma for l in last], dtype=float)


def inv_actions(method: str) -> np.ndarray:
    order_to = np.array([14.0, 24.0, 36.0, 52.0, 72.0, 96.0])
    theta = np.array([0.60, 1.00, 1.55, 2.20]) if method == 'nbo_full_ndu_inventory' else np.array([1.00])
    return np.array([[s, th] for s in order_to for th in theta], dtype=float)


def inv_spec(method: str) -> NBOSpec:
    horizon = 40
    shocks = np.array([[u, dz] for u in (0.15, 0.50, 0.85) for dz in (-1.0, 0.0, 1.0)], dtype=float)

    def terminal(X):
        inv, backlog = X[:, 0], X[:, 1]
        return -0.15 * inv - 2.0 * backlog

    def tr(step, X, action, shock):
        inventory, backlog, ewma, last_demand = X[:, 0], X[:, 1], X[:, 2], X[:, 3]
        order_up_to, theta = action
        if method == 'nbo_fixed_service_inventory':
            order_up_to = 36.0
            theta = 1.0
        q = np.maximum(0.0, order_up_to + 0.35 * backlog - inventory)
        inventory2 = inventory + q
        u, dz = shock
        p_high = 0.12 + 0.35 * sigmoid((last_demand - ewma) / 5.0)
        high = (u < p_high).astype(float)
        seasonal = 2.5 * math.sin(2.0 * math.pi * step / 20.0)
        mean = 18.0 + seasonal + high * 10.0
        sd = 3.0 + high * 1.5
        demand = np.maximum(0.0, np.rint(mean + sd * dz)).astype(float)
        need = backlog + demand
        filled = np.minimum(inventory2, need)
        invn = inventory2 - filled
        bkn = need - filled
        fill = np.where(need <= 1e-9, 1.0, filled / need)
        holding_cost = 0.28 * invn
        shortage_cost = 2.85 * bkn
        order_cost = 0.055 * q + 0.010 * np.maximum(0.0, q - 35.0) ** 2 / 35.0
        theta_cost = 0.045 * (theta - 1.0) ** 2
        cost = holding_cost + shortage_cost + order_cost + theta_cost
        reward = -cost + 8.0 * theta * (fill - 0.92) - 0.03 * theta * (fill < 0.92)
        ewmn = 0.82 * ewma + 0.18 * demand
        return np.stack([np.clip(invn, 0.0, 115.0), np.clip(bkn, 0.0, 80.0), np.clip(ewmn, 5.0, 50.0), np.clip(demand, 0.0, 60.0)], axis=1), reward

    return NBOSpec('inventory_service_level', method, horizon, inv_grid(), inv_actions(method), shocks, tr, terminal)


def eval_inventory(policy: NBOResult, seed: int, episodes: int = 512) -> dict[str, float]:
    rng = np.random.default_rng(seed)
    H = 40
    inventory = np.full(episodes, 26.0)
    backlog = np.zeros(episodes)
    ewma = np.full(episodes, 22.0)
    last_demand = np.full(episodes, 22.0)
    high = np.zeros(episodes, dtype=bool)
    total_cost = np.zeros(episodes)
    total_cost_no_theta = np.zeros(episodes)
    total_demand = np.zeros(episodes)
    total_filled = np.zeros(episodes)
    total_order = np.zeros(episodes)
    total_inventory = np.zeros(episodes)
    service_breach = np.zeros(episodes)
    total_reward = np.zeros(episodes)
    theta_path = []
    for t in range(H):
        action = nbo_actions(policy, t, np.stack([inventory, backlog, ewma, last_demand], axis=1))
        order_to, theta = action[:, 0], action[:, 1]
        if policy.method == 'nbo_fixed_service_inventory':
            order_to = np.full(episodes, 36.0)
            theta = np.ones(episodes)
        q = np.maximum(0.0, order_to + 0.35 * backlog - inventory)
        inventory = inventory + q
        flips_down = rng.random(episodes) < 0.08
        flips_up = rng.random(episodes) < 0.12
        high = np.where(high, ~flips_down, flips_up)
        seasonal = 2.5 * math.sin(2.0 * math.pi * t / 20.0)
        mean = 18.0 + seasonal + high.astype(float) * 10.0
        sd = 3.0 + high.astype(float) * 1.5
        demand = np.maximum(0.0, np.rint(rng.normal(mean, sd))).astype(float)
        need = backlog + demand
        filled = np.minimum(inventory, need)
        inventory = inventory - filled
        backlog = need - filled
        fill_rate_t = np.where(need <= 1e-9, 1.0, filled / need)
        service_breach += fill_rate_t < 0.92
        holding_cost = 0.28 * inventory
        shortage_cost = 2.85 * backlog
        order_cost = 0.055 * q + 0.010 * np.maximum(0.0, q - 35.0) ** 2 / 35.0
        theta_cost = 0.045 * (theta - 1.0) ** 2
        cost = holding_cost + shortage_cost + order_cost + theta_cost
        total_cost += cost
        total_cost_no_theta += holding_cost + shortage_cost + order_cost
        total_reward += -cost + 8.0 * theta * (fill_rate_t - 0.92) - 0.03 * theta * (fill_rate_t < 0.92)
        total_demand += demand
        total_filled += filled
        total_order += q
        total_inventory += inventory
        theta_path.append(theta)
        ewma = 0.82 * ewma + 0.18 * demand
        last_demand = demand
    fill_rate = total_filled / np.maximum(total_demand, 1.0)
    avg_cost = total_cost / H
    avg_cost_no_theta = total_cost_no_theta / H
    avg_inventory = total_inventory / H
    avg_order = total_order / H
    theta_stack = np.vstack(theta_path)
    welfare = total_reward / H
    return {
        'mean_welfare': float(np.mean(welfare)),
        'avg_cost': float(np.mean(avg_cost)),
        'avg_cost_no_theta': float(np.mean(avg_cost_no_theta)),
        'fill_rate': float(np.mean(fill_rate)),
        'ending_backlog': float(np.mean(backlog)),
        'avg_inventory': float(np.mean(avg_inventory)),
        'avg_order': float(np.mean(avg_order)),
        'theta_std': float(np.mean(np.std(theta_stack, axis=0))),
        'service_breach_count': float(np.mean(service_breach)),
    }


def solve_all(width: int = 32) -> list[NBOResult]:
    specs = []
    for method in ['nbo_full_ndu', 'nbo_fixed_pref', 'nbo_preference_only']:
        specs.append(exp1_spec(method))
    for method in ['nbo_full_ndu', 'nbo_fixed_pref_recurrent', 'nbo_oracle_joint_action']:
        specs.append(exp2_spec(method))
    for method in ['nbo_full_ndu', 'nbo_fixed_pref_joint', 'nbo_oracle_factor']:
        specs.append(exp3_spec(method))
    for method in ['nbo_full_ndu_inventory', 'nbo_action_only_inventory', 'nbo_fixed_service_inventory']:
        specs.append(inv_spec(method))
    policies = []
    for i, spec in enumerate(specs):
        print(f'[nbo] solving {spec.experiment}/{spec.method}: sensors={len(spec.state_grid)} actions={len(spec.actions)} horizon={spec.horizon}', flush=True)
        t0 = time.time()
        pol = solve_nbo(spec, seed=20260512 + 1000 * i, width=width)
        print(f'[nbo] solved {spec.experiment}/{spec.method} residual_mean={np.mean(pol.residuals):.6g} elapsed={time.time()-t0:.1f}s', flush=True)
        policies.append(pol)
    return policies


def eval_policy(policy: NBOResult, seed: int) -> dict[str, float]:
    if policy.experiment == 'exp1_habit_portfolio':
        return eval_exp1(policy, seed)
    if policy.experiment == 'exp2_hidden_regime':
        return eval_exp2(policy, seed)
    if policy.experiment == 'exp3_high_dimensional_allocation':
        return eval_exp3(policy, seed)
    if policy.experiment == 'inventory_service_level':
        return eval_inventory(policy, seed)
    raise ValueError(policy.experiment)


def write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open('w', newline='') as fh:
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def summarize(rows: list[dict]) -> list[dict]:
    groups = sorted({(r['experiment'], r['method']) for r in rows})
    metric_keys = sorted({k for r in rows for k in r if k not in {'experiment', 'method', 'seed', 'seed_index', 'nbo_state_dim', 'nbo_action_dim', 'nbo_sensor_count', 'nbo_action_count', 'nbo_horizon', 'nbo_shock_count', 'nbo_residual_mean', 'nbo_residual_max'}})
    out = []
    for exp, method in groups:
        rs = [r for r in rows if r['experiment'] == exp and r['method'] == method]
        row = {
            'experiment': exp,
            'method': method,
            'seed_count': len(rs),
            'nbo_state_dim': rs[0]['nbo_state_dim'],
            'nbo_action_dim': rs[0]['nbo_action_dim'],
            'nbo_sensor_count': rs[0]['nbo_sensor_count'],
            'nbo_action_count': rs[0]['nbo_action_count'],
            'nbo_horizon': rs[0]['nbo_horizon'],
            'nbo_shock_count': rs[0]['nbo_shock_count'],
            'nbo_residual_mean': rs[0]['nbo_residual_mean'],
            'nbo_residual_max': rs[0]['nbo_residual_max'],
        }
        for key in metric_keys:
            vals = [float(r[key]) for r in rs if key in r and r[key] != '']
            if not vals:
                continue
            mean = sum(vals) / len(vals)
            ci = 1.96 * (stats.stdev(vals) / math.sqrt(len(vals))) if len(vals) > 1 else 0.0
            row[key] = mean
            row[f'{key}_ci95'] = ci
        out.append(row)
    return out


def residual_rows(policies: list[NBOResult]) -> list[dict]:
    out = []
    for pol in policies:
        out.append({
            'experiment': pol.experiment,
            'method': pol.method,
            'nbo_state_dim': pol.state_dim,
            'nbo_action_dim': pol.action_dim,
            'nbo_sensor_count': pol.sensor_count,
            'nbo_action_count': pol.action_count,
            'nbo_horizon': pol.horizon,
            'nbo_shock_count': pol.shock_count,
            'mean_bellman_fit_rmse': float(np.mean(pol.residuals)),
            'max_bellman_fit_rmse': float(np.max(pol.residuals)),
            'final_step_bellman_fit_rmse': float(pol.residuals[-1]),
            'algorithm': 'nbo_style_fitted_bellman_recursion_numpy',
        })
    return out


